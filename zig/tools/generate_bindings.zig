const std = @import("std");
const builtin = @import("builtin");

fn writeEnum(writer: *std.Io.Writer, allocator: std.mem.Allocator, name: []const u8, comptime T: type) !void {
    try writer.print("\n\nclass {s}(Enum):\n", .{name});
    const info = @typeInfo(T).@"enum";

    inline for (info.field_names, info.field_values) |field_name, field_value| {
        const upper = try std.ascii.allocUpperString(allocator, field_name);
        defer allocator.free(upper);
        try writer.print("    {s} = {d}\n", .{ upper, field_value });
    }

    if (T == std.zig.Ast.Node.Tag) {
        try writer.writeAll("    OR_ELSE = ORELSE  # Backward-compatible Python spelling.\n");
    }
}

fn bindingsMatch(init: std.process.Init, path: []const u8, expected: []const u8) !bool {
    const existing = std.Io.Dir.cwd().readFileAlloc(init.io, path, init.gpa, .unlimited) catch |err| switch (err) {
        error.FileNotFound => return false,
        else => return err,
    };
    defer init.gpa.free(existing);
    const normalized = try std.mem.replaceOwned(u8, init.gpa, existing, "\r\n", "\n");
    defer init.gpa.free(normalized);
    return std.mem.eql(u8, normalized, expected);
}

pub fn main(init: std.process.Init) !void {
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    if (args.len != 3 or
        (!std.mem.eql(u8, args[1], "--check") and !std.mem.eql(u8, args[1], "--update")))
    {
        std.log.err("Usage: generate-bindings <--check|--update> <bindings-file>", .{});
        return error.InvalidArguments;
    }
    const check_only = std.mem.eql(u8, args[1], "--check");

    var output: std.Io.Writer.Allocating = .init(init.gpa);
    defer output.deinit();
    const writer = &output.writer;

    try writer.print(
        "# Generated by `zig build bindings` with Zig {s}. Do not edit.\nfrom enum import Enum\n",
        .{builtin.zig_version_string},
    );
    try writeEnum(writer, init.gpa, "NodeTag", std.zig.Ast.Node.Tag);
    try writeEnum(writer, init.gpa, "TokenTag", std.zig.Token.Tag);
    try writeEnum(writer, init.gpa, "ErrorTag", std.zig.Ast.Error.Tag);

    if (try bindingsMatch(init, args[2], output.written())) return;
    if (check_only) {
        std.log.err("Python AST enums are missing or out of date. Run `zig build bindings` to update.", .{});
        return error.StaleBindings;
    }
    try std.Io.Dir.cwd().writeFile(init.io, .{ .sub_path = args[2], .data = output.written() });
}
